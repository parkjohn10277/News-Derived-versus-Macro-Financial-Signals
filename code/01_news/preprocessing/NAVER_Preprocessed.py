import pandas as pd
import re
import html
import unicodedata
from pathlib import Path


# ============================================================
# 1. 파일 경로
# ============================================================

INPUT_FILE = Path(
    r".\1_News\NAVER_0319_2026\naver.csv"
)

OUTPUT_FILE = (
    INPUT_FILE.parent
    / "naver_preprocessed_20150227.csv"
)

# 2015-02-27부터 사용
CUTOFF_DATE = pd.Timestamp("2015-02-27")


# ============================================================
# 2. CSV 읽기
# ============================================================

def read_csv_auto(file_path):

    encodings = [
        "utf-8-sig",
        "utf-8",
        "cp949",
        "euc-kr"
    ]

    for enc in encodings:

        try:

            df = pd.read_csv(
                file_path,
                encoding=enc,
                low_memory=False
            )

            print(f"CSV 인코딩: {enc}")

            return df

        except UnicodeDecodeError:
            continue

    raise ValueError(
        "CSV 인코딩을 확인할 수 없습니다."
    )


df = read_csv_auto(INPUT_FILE)


print("=" * 70)
print(f"원본 뉴스: {len(df):,}건")
print("컬럼:", list(df.columns))
print("=" * 70)


# ============================================================
# 3. 날짜 처리
# ============================================================

DATE_COLUMN = "보도일자"


if DATE_COLUMN not in df.columns:

    raise ValueError(
        f"'{DATE_COLUMN}' 컬럼이 없습니다.\n"
        f"현재 컬럼: {list(df.columns)}"
    )


# 날짜 변환
df[DATE_COLUMN] = pd.to_datetime(
    df[DATE_COLUMN],
    errors="coerce"
)


# 날짜 변환 실패
invalid_dates = (
    df[DATE_COLUMN]
    .isna()
    .sum()
)

print(
    f"날짜 변환 실패: "
    f"{invalid_dates:,}건"
)


# 날짜 없는 기사 제거
df = df.dropna(
    subset=[DATE_COLUMN]
)


# ============================================================
# 4. 2015-02-27 이전 기사 삭제
# ============================================================

before_date_filter = len(df)


df = df[
    df[DATE_COLUMN] >= CUTOFF_DATE
].copy()


removed_old_news = (
    before_date_filter
    - len(df)
)


print(
    f"2015-02-27 이전 뉴스 삭제: "
    f"{removed_old_news:,}건"
)


# ============================================================
# 5. 뉴스 텍스트 전처리 함수
# ============================================================

def clean_news_text(text):

    if pd.isna(text):
        return ""

    text = str(text)


    # --------------------------------------------------------
    # Unicode 정규화
    # 깨진 전각문자, 호환문자 일부 정리
    # --------------------------------------------------------

    text = unicodedata.normalize(
        "NFKC",
        text
    )


    # --------------------------------------------------------
    # HTML entity 변환
    #
    # &amp; → &
    # &quot; → "
    # --------------------------------------------------------

    text = html.unescape(text)


    # --------------------------------------------------------
    # HTML 태그 제거
    #
    # <b>삼성전자</b>
    # → 삼성전자
    # --------------------------------------------------------

    text = re.sub(
        r"<[^>]+>",
        " ",
        text
    )


    # --------------------------------------------------------
    # 보이지 않는 문자 / 깨진 문자 제거
    # --------------------------------------------------------

    invisible_chars = [
        "\ufeff",
        "\u200b",
        "\u200c",
        "\u200d",
        "\u2060",
        "\xa0",
        "�"
    ]

    for ch in invisible_chars:
        text = text.replace(
            ch,
            " "
        )


    # --------------------------------------------------------
    # 제어 문자 제거
    # --------------------------------------------------------

    text = re.sub(
        r"[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]",
        " ",
        text
    )


    # --------------------------------------------------------
    # 뉴스 장식용 특수기호 제거
    # --------------------------------------------------------

    text = re.sub(
        r"[■□▪▫◆◇●○◎▲△▼▽▶▷◀◁★☆※☞☜"
        r"→←↑↓♠♣♥♦☎☏✓✔]",
        " ",
        text
    )


    # --------------------------------------------------------
    # 반복 기호 정리
    # --------------------------------------------------------

    text = re.sub(
        r"!{2,}",
        "!",
        text
    )

    text = re.sub(
        r"\?{2,}",
        "?",
        text
    )

    text = re.sub(
        r"\.{3,}",
        ".",
        text
    )


    # --------------------------------------------------------
    # 불필요한 특수기호 제거
    #
    # 금융뉴스에서 의미 있을 수 있는
    # %, +, -, $, ₩ 등은 유지
    # --------------------------------------------------------

    text = re.sub(
        r"""[^
        가-힣
        ㄱ-ㅎ
        ㅏ-ㅣ
        A-Za-z
        0-9
        \s
        \.\,\!\?
        \%\+\-
        \/:
        ;
        \(\)
        \[\]
        '"
        ₩$
        ]""",
        " ",
        text,
        flags=re.VERBOSE
    )


    # --------------------------------------------------------
    # 여러 공백 → 한 칸
    # --------------------------------------------------------

    text = re.sub(
        r"\s+",
        " ",
        text
    )


    return text.strip()


# ============================================================
# 6. 제목 / 요약내용 전처리
# ============================================================

TEXT_COLUMNS = [
    "제목",
    "요약내용"
]


for col in TEXT_COLUMNS:

    if col in df.columns:

        print(
            f"텍스트 전처리 중: {col}"
        )

        df[col] = df[col].apply(
            clean_news_text
        )


# ============================================================
# 7. 제목과 요약이 둘 다 없는 기사 제거
# ============================================================

empty_news = (
    df["제목"]
    .fillna("")
    .str.strip()
    .eq("")
    &
    df["요약내용"]
    .fillna("")
    .str.strip()
    .eq("")
)


empty_news_count = (
    empty_news.sum()
)


df = df[
    ~empty_news
].copy()


print(
    f"제목·요약 모두 없는 뉴스 삭제: "
    f"{empty_news_count:,}건"
)


# ============================================================
# 8. 날짜순 정렬
# ============================================================

df = (
    df
    .sort_values(
        "보도일자"
    )
    .reset_index(
        drop=True
    )
)


# ============================================================
# 9. 날짜 형식 통일
# ============================================================

df["보도일자"] = (
    df["보도일자"]
    .dt.strftime(
        "%Y-%m-%d"
    )
)

# ============================================================
# 10. 불필요한 컬럼 삭제
# ============================================================

DROP_COLUMNS = [
    "언어",
    "내용길이"
]

df = df.drop(
    columns=[
        col for col in DROP_COLUMNS
        if col in df.columns
    ]
)

# ============================================================
# 11. 저장
# ============================================================

df.to_csv(
    OUTPUT_FILE,
    index=False,
    encoding="utf-8-sig"
)


# ============================================================
# 12. 결과 출력
# ============================================================

print("\n" + "=" * 70)

print("NAVER 뉴스 전처리 완료")

print("=" * 70)

print(
    f"최종 뉴스 수: "
    f"{len(df):,}건"
)

print(
    f"2015-02-27 이전 삭제: "
    f"{removed_old_news:,}건"
)

print(
    f"최초 날짜: "
    f"{df['보도일자'].min()}"
)

print(
    f"최종 날짜: "
    f"{df['보도일자'].max()}"
)

print(
    f"\n저장 위치:\n"
    f"{OUTPUT_FILE}"
)

print("=" * 70)